// HandlerConfig is what the HTTP layer needs besides the Service.
type HandlerConfig struct {
	// WebOrigins is the exact-match allowlist of browser origins (P-04); nothing else passes CSRF.
	WebOrigins []string
	// TrustedProxyHops is the httpx.ClientIP hop count (0: RemoteAddr only).
	TrustedProxyHops int
	// ProxySecrets are the accepted X-Swastik-Proxy-Key values (PROXY_SHARED_SECRETS): a request
	// carrying one may name the client address in X-Swastik-Client-IP. Empty trusts no such header.
	ProxySecrets []string
	// Limiter is the per-IP limiter of sign-in, refresh, mfa-verify and enrolment (P-17). Nil means
	// the default: 30 requests per minute per IP.
	Limiter *ratelimit.Limiter
}

// Default per-IP limit of the credential operations (plan P-17).
const (
	defaultRateLimit   = 30
	defaultRateWindow  = time.Minute
	defaultRateMaxKeys = 10_000
)

type handlers struct {
	svc     *Service
	cfg     HandlerConfig
	limiter *ratelimit.Limiter
	origins map[string]struct{}
}

// Register adds the auth operations to the API. Every operation declares its Security through
// platform/authz. With a nil svc (the `openapi` command and the static contract walk) the
// operations still register; they are never called with credentials that could pass.
func Register(api huma.API, svc *Service, cfg HandlerConfig) {
	h := &handlers{svc: svc, cfg: cfg, limiter: cfg.Limiter, origins: map[string]struct{}{}}
	if h.limiter == nil {
		h.limiter = ratelimit.New(defaultRateLimit, defaultRateWindow, defaultRateMaxKeys, clock.Real)
	}
	for _, o := range cfg.WebOrigins {
		h.origins[o] = struct{}{}
	}
	h.registerSessions(api)
	h.registerMFA(api)
	h.registerAdmin(api)
}

// ---- wire types (contracts/openapi-auth.yaml; snake_case JSON) ----

// DeviceInfoRequest is the installation that signs in.
type DeviceInfoRequest struct {
	ID       string `json:"id" format:"uuid" doc:"Installation identity generated by the app."`
	Name     string `json:"name" minLength:"1" maxLength:"100"`
	Platform string `json:"platform" enum:"android,iphone,web"`
}

// SignInRequest is the password step.
type SignInRequest struct {
	Identifier string            `json:"identifier" minLength:"1" maxLength:"320" doc:"Email, or an Indian mobile number in any accepted form."`
	Password   string            `json:"password" minLength:"1" maxLength:"1024" format:"password"`
	ClientType string            `json:"client_type" enum:"mobile,web" doc:"mobile: the refresh token is in the body. web: only in an HttpOnly cookie."`
	Device     DeviceInfoRequest `json:"device"`
}

// SessionUser is the signed-in user in a session response.
type SessionUser struct {
	ID    string `json:"id" format:"uuid"`
	Role  string `json:"role" enum:"admin,client"`
	Name  string `json:"name"`
	Email string `json:"email"`
}

// SessionResponse is a session: tokens and lifetimes.
type SessionResponse struct {
	AccessToken          string      `json:"access_token"`
	TokenType            string      `json:"token_type" enum:"Bearer"`
	AccessTokenExpiresAt time.Time   `json:"access_token_expires_at"`
	RefreshToken         string      `json:"refresh_token,omitempty" doc:"Only for client_type mobile (drt_...). Web sessions get an HttpOnly cookie instead."`
	SessionID            string      `json:"session_id" format:"uuid"`
	SessionExpiresAt     time.Time   `json:"session_expires_at" doc:"Absolute expiry."`
	IdleExpiresAt        time.Time   `json:"idle_expires_at"`
	User                 SessionUser `json:"user"`
}

// ChallengeResponse is the interim proof of an admin whose password was correct.
type ChallengeResponse struct {
	ChallengeToken string    `json:"challenge_token" doc:"dmc_...; send as Authorization: Bearer to the second-factor operations only."`
	ExpiresAt      time.Time `json:"expires_at"`
}

// SignInResponse is the outcome of a correct password.
type SignInResponse struct {
	NextStep  string             `json:"next_step" enum:"signed_in,mfa_required,mfa_enrolment_required"`
	Session   *SessionResponse   `json:"session,omitempty" doc:"Present when next_step is signed_in."`
	Challenge *ChallengeResponse `json:"challenge,omitempty" doc:"Present when next_step is mfa_required or mfa_enrolment_required."`
}

// RefreshRequest is one refresh attempt.
type RefreshRequest struct {
	DeviceID     string `json:"device_id" format:"uuid"`
	RefreshToken string `json:"refresh_token,omitempty" maxLength:"128" doc:"Mobile only. Omit for web (the cookie is used)."`
}

// ChangePasswordRequest is a password change.
type ChangePasswordRequest struct {
	CurrentPassword string `json:"current_password" minLength:"1" maxLength:"1024" format:"password"`
	NewPassword     string `json:"new_password" minLength:"1" maxLength:"2048" format:"password" doc:"The password policy is enforced with specific codes."`
}

// DeviceItem is one live device session.
type DeviceItem struct {
	SessionID    string    `json:"session_id" format:"uuid"`
	DeviceName   string    `json:"device_name"`
	Platform     string    `json:"platform" enum:"android,iphone,web"`
	SignedInAt   time.Time `json:"signed_in_at"`
	LastActiveAt time.Time `json:"last_active_at"`
	IsCurrent    bool      `json:"is_current" doc:"Always false in admin listings of another user."`
}

// DeviceList is a list of device sessions.
type DeviceList struct {
	Items []DeviceItem `json:"items"`
}

// ---- helpers ----

func toSessionResponse(s SessionTokens, web bool) SessionResponse {
	out := SessionResponse{
		AccessToken: s.AccessToken, TokenType: "Bearer", AccessTokenExpiresAt: s.AccessTokenExpiresAt.UTC(),
		SessionID: s.SessionID.String(), SessionExpiresAt: s.SessionExpiresAt.UTC(), IdleExpiresAt: s.IdleExpiresAt.UTC(),
		User: SessionUser{ID: s.User.ID.String(), Role: s.User.Role, Name: s.User.Name, Email: s.User.Email},
	}
	if !web {
		out.RefreshToken = s.RefreshToken
	}
	return out
}

// cookieFor is the Set-Cookie header of a web session, empty for a mobile one.
func (h *handlers) cookieFor(s SessionTokens, web bool) string {
	if !web {
		return ""
	}
	return refreshCookie(s.RefreshToken, s.SessionExpiresAt, h.svc.now())
}

// ready is a 503 when the API was built without a Service (never in production).
func (h *handlers) ready() error {
	if h.svc == nil {
		return httpx.Problem(http.StatusServiceUnavailable, CodeNotConfigured, "The auth service is not configured.")
	}
	return nil
}

// fail maps a domain error to its RFC 9457 problem. Anything unknown is a bare 500 and is logged
// (the error text carries no secret: services never put one in an error).
func (h *handlers) fail(ctx context.Context, err error) error {
	switch {
	case errors.Is(err, ErrInvalidCredentials):
		return httpx.Problem(http.StatusUnauthorized, CodeInvalidCredentials, "The credentials are not valid.")
	case errors.Is(err, ErrRefreshRejected):
		return httpx.Problem(http.StatusUnauthorized, CodeRefreshRejected, "The session cannot be refreshed; sign in again.")
	case errors.Is(err, ErrInvalidChallenge):
		return httpx.Problem(http.StatusUnauthorized, CodeUnauthenticated, "The second-factor proof is not valid.")
	case errors.Is(err, ErrReauthFailed):
		return httpx.Problem(http.StatusForbidden, CodeReauthFailed, "Re-authentication failed.")
	case errors.Is(err, ErrBusy):
		return httpx.Problem(http.StatusServiceUnavailable, CodeBusy, "The server is busy; try again shortly.")
	}
	p := ProblemFor(err)
	var se huma.StatusError
	if errors.As(p, &se) && se.GetStatus() == http.StatusInternalServerError {
		h.svc.log.ErrorContext(ctx, "auth: unexpected error", "err", err)
	}
	return p
}

func parseUUID(s string) uuid.UUID {
	id, _ := uuid.Parse(s) // the schema validated the format; a bad value would be uuid.Nil
	return id
}

// isWeb reports whether the session is a web session (it owns the refresh cookie).
func (h *handlers) isWeb(ctx context.Context, session uuid.UUID) bool {
	ss, err := h.svc.store.GetSession(ctx, session)
	return err == nil && ss.ClientType == ClientTypeWeb
}

// ---- operations: sign-in, refresh, sign-out, devices, password ----

type signInInput struct {
	Origin string `header:"Origin" doc:"Required for web requests: must equal an allowed admin panel origin."`
	CSRF   string `header:"X-Swastik-CSRF" doc:"Required for web requests: must be 1."`
	Body   SignInRequest
}

type signInOutput struct {
	SetCookie string `header:"Set-Cookie"`
	Body      SignInResponse
}

type refreshInput struct {
	Origin string `header:"Origin" doc:"Required for web requests: must equal an allowed admin panel origin."`
	CSRF   string `header:"X-Swastik-CSRF" doc:"Required for web requests: must be 1."`
	Cookie string `cookie:"__Secure-swastik_rt" doc:"The refresh token of a web session."`
	Body   RefreshRequest
}

type sessionOutput struct {
	SetCookie string `header:"Set-Cookie"`
	Body      SessionResponse
}

type cookieOnlyOutput struct {
	SetCookie string `header:"Set-Cookie"`
}

type deviceIDInput struct {
	SessionID string `path:"sessionId" format:"uuid"`
}

type deviceListOutput struct{ Body DeviceList }

type changePasswordInput struct{ Body ChangePasswordRequest }

func (h *handlers) registerSessions(api huma.API) {
	limited := huma.Middlewares{h.ingress(true)}
	huma.Register(api, huma.Operation{
		OperationID: "auth-sign-in", Method: http.MethodPost, Path: "/v1/auth/sign-in", Tags: []string{"Auth"},
		Summary: "Sign in with email or mobile and password", Security: authz.Public(), Middlewares: limited,
	}, h.signIn)
	huma.Register(api, huma.Operation{
		OperationID: "auth-refresh", Method: http.MethodPost, Path: "/v1/auth/refresh", Tags: []string{"Auth"},
		Summary: "Rotate the refresh token and get a new access token", Security: authz.Public(), Middlewares: limited,
	}, h.refresh)
	huma.Register(api, huma.Operation{
		OperationID: "auth-sign-out", Method: http.MethodPost, Path: "/v1/auth/sign-out", Tags: []string{"Auth"},
		Summary: "End this session", Security: authz.Require(), DefaultStatus: http.StatusNoContent,
	}, h.signOut)
	huma.Register(api, huma.Operation{
		OperationID: "auth-sign-out-everywhere", Method: http.MethodPost, Path: "/v1/auth/sign-out-everywhere", Tags: []string{"Auth"},
		Summary: "End every session of the caller, this one included", Security: authz.Require(), DefaultStatus: http.StatusNoContent,
	}, h.signOutEverywhere)
	huma.Register(api, huma.Operation{
		OperationID: "auth-devices-list", Method: http.MethodGet, Path: "/v1/auth/devices", Tags: []string{"Auth"},
		Summary: "List the caller's live device sessions", Security: authz.Require(),
	}, h.devices)
	huma.Register(api, huma.Operation{
		OperationID: "auth-device-revoke", Method: http.MethodDelete, Path: "/v1/auth/devices/{sessionId}", Tags: []string{"Auth"},
		Summary: "End one of the caller's own device sessions", Security: authz.Require(), DefaultStatus: http.StatusNoContent,
	}, h.revokeDevice)
	huma.Register(api, huma.Operation{
		OperationID: "auth-password-change", Method: http.MethodPost, Path: "/v1/auth/password/change", Tags: []string{"Auth"},
		Summary: "Change the caller's password", Security: authz.Require(), DefaultStatus: http.StatusNoContent,
		Middlewares: huma.Middlewares{h.ingress(false)},
	}, h.changePassword)
}

func (h *handlers) signIn(ctx context.Context, in *signInInput) (*signInOutput, error) {
	if err := h.ready(); err != nil {
		return nil, err
	}
	web := in.Body.ClientType == ClientTypeWeb
	if web { // decided before the password is looked at: a rejected request counts and writes nothing
		if err := h.checkBrowserRequest(in.Origin, in.CSRF); err != nil {
			return nil, err
		}
	}
	d := in.Body.Device
	res, err := h.svc.SignIn(ctx, SignInInput{
		Identifier: in.Body.Identifier, Password: in.Body.Password, ClientType: in.Body.ClientType,
		Device: DeviceInfo{ID: parseUUID(d.ID), Name: d.Name, Platform: d.Platform}, IP: ipOf(ctx),
	})
	if err != nil {
		return nil, h.fail(ctx, err)
	}
	out := &signInOutput{Body: SignInResponse{NextStep: res.NextStep}}
	if res.Session != nil {
		s := toSessionResponse(*res.Session, web)
		out.Body.Session = &s
		out.SetCookie = h.cookieFor(*res.Session, web)
	}
	if res.Challenge != nil {
		out.Body.Challenge = &ChallengeResponse{ChallengeToken: res.Challenge.Token, ExpiresAt: res.Challenge.ExpiresAt.UTC()}
	}
	return out, nil
}

func (h *handlers) refresh(ctx context.Context, in *refreshInput) (*sessionOutput, error) {
	if err := h.ready(); err != nil {
		return nil, err
	}
	token, clientType := in.Body.RefreshToken, ClientTypeMobile
	if token == "" && in.Cookie != "" { // the credential comes from the cookie: browser rules apply
		if err := h.checkBrowserRequest(in.Origin, in.CSRF); err != nil {
			return nil, err
		}
		token, clientType = in.Cookie, ClientTypeWeb
	}
	s, err := h.svc.Refresh(ctx, RefreshInput{DeviceID: parseUUID(in.Body.DeviceID), RefreshToken: token, ClientType: clientType, IP: ipOf(ctx)})
	if err != nil {
		return nil, h.fail(ctx, err)
	}
	web := clientType == ClientTypeWeb
	return &sessionOutput{SetCookie: h.cookieFor(s, web), Body: toSessionResponse(s, web)}, nil
}

func (h *handlers) signOut(ctx context.Context, _ *struct{}) (*cookieOnlyOutput, error) {
	if err := h.ready(); err != nil {
		return nil, err
	}
	p := authz.MustPrincipal(ctx)
	out := &cookieOnlyOutput{}
	if h.isWeb(ctx, p.SessionID) {
		out.SetCookie = clearedRefreshCookie()
	}
	if err := h.svc.SignOut(ctx, p); err != nil {
		return nil, h.fail(ctx, err)
	}
	return out, nil
}

func (h *handlers) signOutEverywhere(ctx context.Context, _ *struct{}) (*cookieOnlyOutput, error) {
	if err := h.ready(); err != nil {
		return nil, err
	}
	p := authz.MustPrincipal(ctx)
	out := &cookieOnlyOutput{}
	if h.isWeb(ctx, p.SessionID) {
		out.SetCookie = clearedRefreshCookie()
	}
	if _, err := h.svc.SignOutEverywhere(ctx, p); err != nil {
		return nil, h.fail(ctx, err)
	}
	return out, nil
}

func (h *handlers) devices(ctx context.Context, _ *struct{}) (*deviceListOutput, error) {
	if err := h.ready(); err != nil {
		return nil, err
	}
	list, err := h.svc.ListDevices(ctx, authz.MustPrincipal(ctx))
	if err != nil {
		return nil, h.fail(ctx, err)
	}
	return &deviceListOutput{Body: toDeviceList(list)}, nil
}

func toDeviceList(devices []Device) DeviceList {
	out := DeviceList{Items: make([]DeviceItem, 0, len(devices))}
	for _, d := range devices {
		out.Items = append(out.Items, DeviceItem{
			SessionID: d.SessionID.String(), DeviceName: d.DeviceName, Platform: d.Platform,
			SignedInAt: d.SignedInAt.UTC(), LastActiveAt: d.LastActiveAt.UTC(), IsCurrent: d.IsCurrent,
		})
	}
	return out
}

func (h *handlers) revokeDevice(ctx context.Context, in *deviceIDInput) (*cookieOnlyOutput, error) {
	if err := h.ready(); err != nil {
		return nil, err
	}
	p := authz.MustPrincipal(ctx)
	id := parseUUID(in.SessionID)
	out := &cookieOnlyOutput{}
	if id == p.SessionID && h.isWeb(ctx, id) {
		out.SetCookie = clearedRefreshCookie()
	}
	if err := h.svc.RevokeDevice(ctx, p, id); err != nil {
		return nil, h.fail(ctx, err)
	}
	return out, nil
}

func (h *handlers) changePassword(ctx context.Context, in *changePasswordInput) (*struct{}, error) {
	if err := h.ready(); err != nil {
		return nil, err
	}
	if err := h.svc.ChangePassword(ctx, h.principal(ctx), in.Body.CurrentPassword, in.Body.NewPassword); err != nil {
		return nil, h.fail(ctx, err)
	}
	return &struct{}{}, nil
}
