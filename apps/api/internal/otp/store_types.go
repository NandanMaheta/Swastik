package otp

import (
	"context"
	"errors"
	"time"

	"github.com/google/uuid"

	"github.com/NandanMaheta/swastik/apps/api/internal/platform/istdate"
)

// The Store contract (slice S08 tests it, S09 implements it in store.go). Semantics shared by
// every method:
//
//   - Every method takes the organisation and filters by it: a row of another org is never read,
//     locked or changed (it reads as absent).
//   - Every time comes from the caller (Now parameters); the database clock is never used.
//   - Reads and plain writes run on the transaction in ctx when there is one, else on the pool.
//     Methods documented "requires a tx" return db.ErrNoTx, touching nothing, when ctx has none.
//   - Errors are the sentinels below or errors.go's ErrNotFound; text never carries a contact,
//     handle, code or proof.

// Store errors.
var (
	// ErrOpenFlowExists is InsertVerification finding another open flow of the same user and purpose.
	ErrOpenFlowExists = errors.New("otp: an open verification already exists")
	// ErrLiveCodeExists is InsertCode finding another live code on the verification.
	ErrLiveCodeExists = errors.New("otp: the verification already has a live code")
	// ErrNoLiveCode is a lock or end of a live code when there is none.
	ErrNoLiveCode = errors.New("otp: no live code")
)

// ContactKind picks one contact of a verification.
type ContactKind string

// The two contacts.
const (
	ContactEmail  ContactKind = "email"
	ContactMobile ContactKind = "mobile"
)

// Metric is a daily counter (FR-017).
type Metric string

// The five counters of otp_daily_counts.
const (
	MetricEmailSent     Metric = "email_sent"
	MetricEmailFailed   Metric = "email_failed"
	MetricLimitRefused  Metric = "limit_refused"
	MetricProofAccepted Metric = "proof_accepted"
	MetricProofRefused  Metric = "proof_refused"
)

// Cancel reasons of a verification and end reasons of a code.
const (
	CancelCancelled  = "cancelled"
	CancelSuperseded = "superseded"
	EndUsed          = "used"
	EndSuperseded    = "superseded"
	EndUsedUp        = "used_up"
	EndCancelled     = "cancelled"
)

// VerificationRow is one otp_verifications row. UserID is uuid.Nil for a password-reset decoy;
// Email, Mobile, CancelReason are "" when NULL.
type VerificationRow struct {
	ID, OrgID, UserID    uuid.UUID
	Purpose              Purpose
	Email, Mobile        string
	EmailDoneAt          *time.Time
	MobileDoneAt         *time.Time
	ResetTokenHash       []byte
	ResetTokenExpiresAt  *time.Time
	FinishedAt           *time.Time
	CancelledAt          *time.Time
	CancelReason         string
	CreatedAt, ExpiresAt time.Time
	UpdatedAt            time.Time
}

// NewVerification is the input of InsertVerification. HandleHash is SHA-256 of the handle (32
// bytes); the id is generated by the database. CreatedAt and UpdatedAt are Now.
type NewVerification struct {
	OrgID, UserID uuid.UUID
	Purpose       Purpose
	HandleHash    []byte
	Email, Mobile string
	Now           time.Time
	ExpiresAt     time.Time
}

// CodeRow is one otp_email_codes row. OutboxKey and EndReason are "" when NULL.
type CodeRow struct {
	ID, OrgID, VerificationID uuid.UUID
	Digest                    []byte
	IssuedAt, ExpiresAt       time.Time
	WrongAttempts             int
	OutboxKey                 string
	EndedAt                   *time.Time
	EndReason                 string
}

// NewCode is the input of InsertCode. The caller picks ID because the digest binds it.
type NewCode struct {
	ID, OrgID, VerificationID uuid.UUID
	Digest                    []byte
	OutboxKey                 string // "" for a decoy
	IssuedAt, ExpiresAt       time.Time
}

// LimitKey names one limit row: the scope and the 32-byte HMAC subject.
type LimitKey struct {
	Scope   LimitScope
	Subject []byte
}

// LimitRow is a locked limit row; a row that did not exist yet comes back with no events.
type LimitRow struct {
	Key       LimitKey
	Events    []time.Time
	UpdatedAt time.Time
}

// Store is the persistence of the module.
type Store interface {
	// InsertVerification creates a verification; ErrOpenFlowExists when the user already has an
	// open flow of that purpose (a decoy, UserID Nil, never conflicts).
	InsertVerification(ctx context.Context, in NewVerification) (VerificationRow, error)
	// GetVerification reads one verification; ErrNotFound when absent or of another org.
	GetVerification(ctx context.Context, org, id uuid.UUID) (VerificationRow, error)
	// LockVerificationByHandle locks the row whose handle hash matches (requires a tx); ErrNotFound.
	LockVerificationByHandle(ctx context.Context, org uuid.UUID, handleHash []byte) (VerificationRow, error)
	// LockVerification locks a verification by id (requires a tx); ErrNotFound.
	LockVerification(ctx context.Context, org, id uuid.UUID) (VerificationRow, error)
	// LockOpenVerification locks the user's open (not cancelled, not finished) flow of the purpose
	// (requires a tx); ErrNotFound when there is none. It is what Start supersedes.
	LockOpenVerification(ctx context.Context, org, user uuid.UUID, p Purpose) (VerificationRow, error)
	// MarkContactDone sets email_done_at or mobile_done_at to now when still NULL; ErrNotFound.
	MarkContactDone(ctx context.Context, org, id uuid.UUID, c ContactKind, now time.Time) error
	// FinishVerification sets finished_at; ErrNotFound when absent or already cancelled/finished.
	FinishVerification(ctx context.Context, org, id uuid.UUID, now time.Time) error
	// CancelVerification sets cancelled_at and the reason (CancelCancelled or CancelSuperseded);
	// ErrNotFound when absent or already cancelled/finished.
	CancelVerification(ctx context.Context, org, id uuid.UUID, reason string, now time.Time) error
	// SetResetGrant stores the SHA-256 of the one-time reset token and its expiry; ErrNotFound.
	SetResetGrant(ctx context.Context, org, id uuid.UUID, tokenHash []byte, expires, now time.Time) error

	// InsertCode creates a live code; ErrLiveCodeExists when the verification has one.
	InsertCode(ctx context.Context, in NewCode) (CodeRow, error)
	// LockLiveCode locks the live code (requires a tx); ErrNoLiveCode.
	LockLiveCode(ctx context.Context, org, verificationID uuid.UUID) (CodeRow, error)
	// EndLiveCode ends the live code with a reason (EndUsed...) and returns it; ErrNoLiveCode.
	EndLiveCode(ctx context.Context, org, verificationID uuid.UUID, reason string, now time.Time) (CodeRow, error)
	// AddWrongAttempt increments the code's counter (1..MaxWrongAttempts) and returns the new
	// value; ErrNoLiveCode when the code is absent or ended.
	AddWrongAttempt(ctx context.Context, org, codeID uuid.UUID, now time.Time) (int, error)

	// InsertProof records a used Firebase proof; false means the fingerprint was already used.
	InsertProof(ctx context.Context, org uuid.UUID, fingerprint []byte, verificationID uuid.UUID, now time.Time) (bool, error)

	// LockLimits creates the missing rows and locks all of them (requires a tx). Rows are locked
	// and returned in the fixed scope order send_contact, send_user, send_ip, check_ip, whatever
	// the order of keys, so concurrent callers cannot deadlock.
	LockLimits(ctx context.Context, org uuid.UUID, keys []LimitKey) ([]LimitRow, error)
	// SaveLimit stores the new event list of a (locked) row; at most 60 events.
	SaveLimit(ctx context.Context, org uuid.UUID, key LimitKey, events []time.Time, now time.Time) error

	// IncrementCount adds one to a daily counter (upsert).
	IncrementCount(ctx context.Context, org uuid.UUID, day istdate.Date, m Metric, now time.Time) error
	// GetCounts reads the counters of one IST day; missing ones are zero.
	GetCounts(ctx context.Context, org uuid.UUID, day istdate.Date) (DailyCounts, error)

	// The purge methods delete at most limit rows and return how many they deleted (FR-015).
	// Verifications with expires_at < cutoff (codes and proofs cascade).
	PurgeVerifications(ctx context.Context, org uuid.UUID, cutoff time.Time, limit int) (int, error)
	// Proofs with used_at < cutoff.
	PurgeProofs(ctx context.Context, org uuid.UUID, cutoff time.Time, limit int) (int, error)
	// Limit rows with updated_at < cutoff.
	PurgeLimits(ctx context.Context, org uuid.UUID, cutoff time.Time, limit int) (int, error)
	// Daily counts with day < cutoff.
	PurgeCounts(ctx context.Context, org uuid.UUID, cutoff istdate.Date, limit int) (int, error)
}
